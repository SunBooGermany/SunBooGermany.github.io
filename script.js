let currentLang = "en";

function setList(id, items) {
  const element = document.getElementById(id);
  element.innerHTML = "";
  items.forEach((item) => {
    const li = document.createElement("li");
    li.textContent = item;
    element.appendChild(li);
  });
}

function setPublications(items) {
  const element = document.getElementById("publication-list");
  element.innerHTML = "";
  items.forEach(([journal, year, title, doi], index) => {
    const a = document.createElement("a");
    a.className = "publication";
    a.href = doi;
    a.target = "_blank";
    a.rel = "noreferrer";
    a.innerHTML = `
      <div class="num">${String(index + 1).padStart(2, "0")}</div>
      <div>
        <div class="meta">${journal} · ${year}</div>
        <h3>${title}</h3>
      </div>
      <div class="doi">DOI ↗</div>
    `;
    element.appendChild(a);
  });
}

function setTimeline(items) {
  const element = document.getElementById("timeline");
  element.innerHTML = "";
  items.forEach(([role, org, period, text]) => {
    const article = document.createElement("article");
    article.className = "timeline-item";
    article.innerHTML = `
      <div class="top">
        <div>
          <h3>${role}</h3>
          <div class="org">${org}</div>
        </div>
        <div class="period">${period}</div>
      </div>
      <p>${text}</p>
    `;
    element.appendChild(article);
  });
}

function applyLanguage(lang) {
  const dict = content[lang];
  document.documentElement.lang = lang === "ko" ? "ko" : "en";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (dict[key]) node.textContent = dict[key];
  });
  setList("featured-list", dict.featured);
  setList("project-list", dict.projects);
  setList("conference-list", dict.conferences);
  setPublications(dict.publications);
  setTimeline(dict.timeline);
  document.getElementById("lang-toggle").textContent = lang === "en" ? "한국어" : "English";
}

document.getElementById("lang-toggle").addEventListener("click", () => {
  currentLang = currentLang === "en" ? "ko" : "en";
  applyLanguage(currentLang);
});

document.getElementById("year").textContent = new Date().getFullYear();
applyLanguage(currentLang);
